-- みんカレポータル: データベースの形を書き出す問い合わせ
-- 読み取りだけで、何も書き換えない。Supabase の SQL Editor に貼って Run し、結果の ddl の列を上から順につなぐと schema.sql の本体になる。
-- 「表を作る文が入っている」という確認が出たら、Run without RLS を選ぶ。表を作る文を文字として並べるだけで、実際には作らない。

with
ext as (
  select 1 as ord, e.extname::text as k,
    'create extension if not exists ' || quote_ident(e.extname) || ' with schema ' || quote_ident(n.nspname) || ';' as ddl
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'
),
seq as (
  select 2, c.relname::text, 'create sequence if not exists public.' || quote_ident(c.relname) || ';'
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype in ('a', 'i'))
),
tbl as (
  select 3, c.relname::text,
    'create table public.' || quote_ident(c.relname) || ' (' || chr(10) || '  ' ||
    string_agg(
      quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || case when a.attidentity = 'a' then ' generated always as identity'
              when a.attidentity = 'd' then ' generated by default as identity' else '' end
      || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
              when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end
      || case when a.attnotnull then ' not null' else '' end,
      ',' || chr(10) || '  ' order by a.attnum)
    || chr(10) || ');'
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
  where n.nspname = 'public' and c.relkind in ('r', 'p')
  group by c.relname
),
con as (
  select case when k.contype = 'f' then 5 else 4 end, c.relname || '.' || k.conname,
    'alter table public.' || quote_ident(c.relname) || ' add constraint ' || quote_ident(k.conname) || ' ' || pg_get_constraintdef(k.oid) || ';'
  from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and k.contype in ('p', 'u', 'c', 'f', 'x')
),
idx as (
  select 6, ic.relname::text, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join pg_class c on c.oid = i.indrelid join pg_class ic on ic.oid = i.indexrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
),
vw as (
  select 7, c.relname::text, 'create or replace view public.' || quote_ident(c.relname) || ' as' || chr(10) || pg_get_viewdef(c.oid, true)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
),
fn as (
  select 8, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
trg as (
  select 9, c.relname || '.' || t.tgname, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where not t.tgisinternal
    and (n.nspname = 'public' or exists (select 1 from pg_proc p where p.oid = t.tgfoid and p.pronamespace = 'public'::regnamespace))
),
rls as (
  select 10, c.relname::text,
    'alter table public.' || quote_ident(c.relname) || ' enable row level security;'
    || case when c.relforcerowsecurity then ' alter table public.' || quote_ident(c.relname) || ' force row level security;' else '' end
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p') and c.relrowsecurity
),
pol as (
  select 11, tablename || '.' || policyname,
    'create policy ' || quote_ident(policyname) || ' on public.' || quote_ident(tablename)
    || ' as ' || lower(permissive) || ' for ' || lower(cmd) || ' to ' || array_to_string(roles, ', ')
    || coalesce(' using (' || qual || ')', '') || coalesce(' with check (' || with_check || ')', '') || ';'
  from pg_policies where schemaname = 'public'
),
tgr as (
  select 12, table_name || '.' || grantee,
    'revoke all on table public.' || quote_ident(table_name) || ' from ' || quote_ident(grantee) || '; grant '
    || string_agg(privilege_type, ', ' order by privilege_type) || ' on table public.' || quote_ident(table_name) || ' to ' || quote_ident(grantee) || ';'
  from information_schema.role_table_grants
  where table_schema = 'public' and grantee in ('anon', 'authenticated')
  group by table_name, grantee
),
facl as (
  select 13, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    case when p.proacl is null then '-- ' || p.proname || ': 実行権限は既定のまま'
    else 'revoke all on function public.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') from public, anon, authenticated;'
      || coalesce((
        select string_agg(' grant execute on function public.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') to '
               || case when x.grantee = 0 then 'public' else quote_ident(r.rolname) end || ';', '')
        from aclexplode(p.proacl) x left join pg_roles r on r.oid = x.grantee
        where x.privilege_type = 'EXECUTE' and (x.grantee = 0 or r.rolname in ('anon', 'authenticated'))
      ), '')
    end
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
pub as (
  select 14, pubname || '.' || tablename, 'alter publication ' || quote_ident(pubname) || ' add table public.' || quote_ident(tablename) || ';'
  from pg_publication_tables where schemaname = 'public'
)
select ord, k, ddl from (
  select * from ext union all select * from seq union all select * from tbl union all select * from con
  union all select * from idx union all select * from vw union all select * from fn union all select * from trg
  union all select * from rls union all select * from pol union all select * from tgr union all select * from facl
  union all select * from pub
) s
order by ord, k;
